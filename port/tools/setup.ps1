#!/usr/bin/env pwsh
# port/tools/setup.ps1 - Windows twin of setup.sh.
#
# Installs emsdk (Emscripten), clones Aurora at the pinned revision and applies
# the patches from port/extern/aurora-patches/, then configures and builds the
# chosen CMake preset. Safe to re-run. Works on Windows PowerShell 5.1 and pwsh.
#
#   ./port/tools/setup.ps1                  # setup + build web-debug
#   ./port/tools/setup.ps1 web-single       # setup + build the offline-file preset
#   ./port/tools/setup.ps1 -NoBuild         # just set up the toolchain
#
# Afterwards, in a fresh shell, re-activate emcc with:  . port/tools/env.ps1
param(
    [ValidateSet("web-debug", "web-release", "web-single", "host-tests")]
    [string]$Preset = "web-debug",
    [switch]$NoBuild
)
$ErrorActionPreference = "Stop"

$PortDir = (Resolve-Path (Join-Path $PSScriptRoot "..")).Path
$Extern  = Join-Path $PortDir "extern"
# Pinned like $AuroraRev: "latest" means CI and a fresh clone can get a
# different compiler from the one the port is known to build with. Override in
# the environment to try a newer one.
$EmsdkVersion = if ($env:EMSDK_VERSION) { $env:EMSDK_VERSION } else { "6.0.9" }
$AuroraRepo = "https://github.com/r-burns/aurora.git"
$AuroraRev  = "e6a6f02ace4146e8a2f648d5c274dbb7dd89665c"

New-Item -ItemType Directory -Force -Path $Extern | Out-Null

foreach ($tool in @("git", "cmake", "ninja", "python")) {
    if (-not (Get-Command $tool -ErrorAction SilentlyContinue)) {
        throw "missing required tool: $tool (install it and re-run)"
    }
}

# Stop on a non-zero exit from any native command we call.
function Invoke-Checked {
    param([Parameter(ValueFromRemainingArguments = $true)] $Args)
    & $Args[0] @($Args[1..($Args.Count - 1)])
    if ($LASTEXITCODE -ne 0) { throw "command failed ($LASTEXITCODE): $($Args -join ' ')" }
}

$EmsdkDir = Join-Path $Extern "emsdk"
if (-not (Test-Path $EmsdkDir)) {
    Invoke-Checked git clone --depth 1 https://github.com/emscripten-core/emsdk.git $EmsdkDir
}
$Emsdk = Join-Path $EmsdkDir "emsdk.bat"
Invoke-Checked $Emsdk install $EmsdkVersion
Invoke-Checked $Emsdk activate $EmsdkVersion

$AuroraDir = Join-Path $Extern "aurora"
if (-not (Test-Path (Join-Path $AuroraDir ".git"))) {
    # Force LF: the patches are LF, so a CRLF checkout makes `git apply` reject
    # them. Aurora is a throwaway build dep, so pinning line endings is correct.
    # ponytail: --3way on apply if a future patch still refuses.
    Invoke-Checked git clone -c core.autocrlf=false $AuroraRepo $AuroraDir
}
Invoke-Checked git -C $AuroraDir config core.autocrlf false
Invoke-Checked git -C $AuroraDir fetch -q origin
Invoke-Checked git -C $AuroraDir checkout -q $AuroraRev
Invoke-Checked git -C $AuroraDir reset -q --hard
Get-ChildItem (Join-Path $PortDir "extern/aurora-patches") -Filter *.patch |
    Sort-Object Name | ForEach-Object {
        Write-Host "applying $($_.Name)"
        Invoke-Checked git -C $AuroraDir apply $_.FullName
    }

# env.ps1: dot-source in a fresh shell to put emcc on PATH (twin of env.sh).
@"
# Generated by setup.ps1 - dot-source this file to put emcc on PATH.
`$env:EMSDK_QUIET = "1"
& "$EmsdkDir\emsdk_env.ps1"
"@ | Set-Content -Encoding ASCII (Join-Path $PortDir "tools/env.ps1")

# Activate emcc in THIS session so the CMake presets' `$env{EMSDK}` resolves.
$env:EMSDK_QUIET = "1"
. (Join-Path $EmsdkDir "emsdk_env.ps1")

if ($NoBuild) {
    Write-Host "`nToolchain ready. To build later:`n  . port/tools/env.ps1`n  cd port; cmake --preset $Preset; cmake --build --preset $Preset"
    return
}

Push-Location $PortDir
try {
    Invoke-Checked cmake --preset $Preset
    Invoke-Checked cmake --build --preset $Preset
} finally {
    Pop-Location
}

Write-Host "`nBuilt '$Preset' into port/build/$Preset."
if ($Preset -eq "web-single") {
    Write-Host "Pack the offline file with:  cd port; python tools/pack_single_html.py build/web-single -o melee-offline.html"
} elseif ($Preset -ne "host-tests") {
    Write-Host "Serve it with:  python -m http.server -d port/build/$Preset 8080"
}
